export function getPublishedProperties(max?: number): Property[] {
  const published = properties.filter((property) => !property.hidden);
  return max === undefined ? published : published.slice(0, max);
}

export function getPublishedPropertyBySlug(slug: string): Property | undefined {
  return getPublishedProperties().find((property) => property.slug === slug);
}

export function getFeaturedProperties(max = 6): Property[] {
  return properties
    .filter((property) => !property.hidden && property.featured)
    .slice(0, max);
}

